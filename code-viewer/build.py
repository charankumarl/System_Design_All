#!/usr/bin/env python3
"""Regenerate data.js from the com.company source tree.

Run this any time you add/edit/remove .java files under
Arrays_problem.java/src/com/company, then reload index.html.
"""
import json
import os
import re

ROOT = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "Arrays_problem.java", "src", "com", "company",
)
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data.js")


def natural_key(s):
    return [int(t) if t.isdigit() else t.lower() for t in re.split(r"(\d+)", s)]


def build_tree(dir_path, rel_path=""):
    entries = sorted(os.listdir(dir_path), key=natural_key)
    folders, files = [], []
    for entry in entries:
        if entry.startswith("."):
            continue
        full = os.path.join(dir_path, entry)
        rel = os.path.join(rel_path, entry) if rel_path else entry
        if os.path.isdir(full):
            # skip build artifact / IDE junk directories
            if entry in (".idea", "out", "target", ".git"):
                continue
            child = build_tree(full, rel)
            if child["children"]:
                folders.append(child)
        elif entry.endswith(".java"):
            files.append({"name": entry, "type": "file", "path": rel.replace(os.sep, "/")})
    return {
        "name": os.path.basename(dir_path),
        "type": "folder",
        "children": folders + files,
    }


def collect_contents(dir_path, rel_path, out):
    for entry in sorted(os.listdir(dir_path), key=natural_key):
        if entry.startswith("."):
            continue
        full = os.path.join(dir_path, entry)
        rel = os.path.join(rel_path, entry) if rel_path else entry
        if os.path.isdir(full):
            if entry in (".idea", "out", "target", ".git"):
                continue
            collect_contents(full, rel, out)
        elif entry.endswith(".java"):
            key = rel.replace(os.sep, "/")
            with open(full, "r", errors="replace") as f:
                out[key] = f.read()


def main():
    tree = build_tree(ROOT)
    contents = {}
    collect_contents(ROOT, "", contents)

    file_count = len(contents)
    with open(OUT, "w") as f:
        f.write("// Auto-generated by build.py — do not edit by hand.\n")
        f.write("const FILE_TREE = " + json.dumps(tree) + ";\n")
        f.write("const FILE_CONTENTS = " + json.dumps(contents) + ";\n")

    print(f"Wrote {OUT} ({file_count} files)")


if __name__ == "__main__":
    main()
